#!/usr/bin/env python3
"""Canonical chemistry table for the openBatteryFlux cell database.

Every chemistry is described here once: its datasheet window, its resistance
and thermal defaults, and the shape of its open-circuit voltage. The shape is
given as a small table of anchor points (state of charge in percent, volts).
`ocv_table()` turns those anchors into the 101 values the app uses - one per
1 % of SOC - with monotone cubic interpolation, so the curve is smooth at
every step, has no overshoot, and passes exactly through each anchor.

Where the anchors come from, per chemistry:

  * LTO, Na-ion: a measured OCV-versus-SOC curve of a commercial cell, digitised
from the open-circuit-voltage dataset published by Battery Design
(https://www.batterydesign.net/chemistry/sodium-ion-battery/, figure "OCV curves
versus other chemistry": an LTO cell, the HiNa 32140 sodium-ion cell and a
second Na-ion cell). The values are read off that graph at 5 % SOC steps, so
they carry the shape of the real cells: the LTO plateau at 2.18-2.23 V, and the
sodium-ion curve with its steep first 10 % followed by the low-SOC shoulder at
10-18 % - a flattening of the curve to ~10 mV/% around 2.56-2.60 V that both
Na-ion cells in that figure show, after which the curve steepens again before
settling into the long 13 mV/% climb. The anchor points there are denser than
5 % so the shelf keeps its corner: that shoulder is what makes a Na-ion
discharge curve recognisable next to a lithium one.

  * NMC, NCA, LFP, LCO: fitted to PyBaMM's published parameter sets - Ecker2015
(graphite/NMC, Ecker et al. 2015), NCA_Kim2011 (graphite/NCA, Kim et al. 2011),
Prada2013 (graphite/LFP, Prada et al. 2013) and Ramadass2004 (graphite/LCO,
Ramadass et al. 2004). Each set's equilibrium OCV is read at zero current and
then warped through the measured 0, 50 and 100 % SOC voltages of that
chemistry, so the curve keeps the library's knee values while taking the shape
of the published cell. This is what gives NCA and LCO curves of their own
instead of an NMC copy shifted by a constant. The 101-point tables are in
ocv_fits.py, generated by fit_ocv_pybamm.py; both are generation-time tools and
the app itself does not need pybamm.

  * LMFP: a measured C/10 charge curve of a commercial LMFP/graphite cell (the
figure supplied for this table; 0-1.86 Ah, digitised pixel by pixel against its
axes). The cell sits at 3.31 V when empty and reaches 4.20 V at full charge. The
curve is one continuous S, not two separated plateaus: a gently rising
3.36-3.60 V stretch up to ~30 % SOC (the Fe2+/Fe3+ redox), a steep 3.65-4.00 V
climb through 40-60 % SOC where the Mn2+/Mn3+ contribution takes over, a flat
4.05-4.09 V shelf over 65-80 %, then the final knee to the 4.2 V cut-off. The
101 values in LMFP_OCV_C10 are that curve, one per 1 % SOC. Charging at C/10
holds the cell within a few mV of its rested OCV, so the measured voltage is
used directly.

  * Li-metal: still the NMC shape stretched to the 4.4 V charge limit, because
no PyBaMM parameter set describes a lithium-metal cell. It is the one curve
here that is a shape by construction rather than a fit.

  * Alkaline: measured zero-load voltage of an AA Zn-MnO2 cell, read at 10 %
steps of delivered capacity from the table in TI application note SLVA203 (Loo
& Keller, "Single-cell battery discharge characteristics using the TPS61070
boost converter", 2004), which the Wikipedia "Alkaline battery" article
reproduces. Only the zero-load column is used: 1.59 V fresh, 1.44 V at 90 %,
1.38 V at 80 %, a flat 1.32-1.26 V stretch over the middle, 1.20 V at 10 % and
1.10 V empty. The loaded columns of the same table sag much lower (0.62 V at
330 mW when empty) because they include the internal-resistance drop, so they
are not open-circuit voltages and are not used here.

  * What could not be fitted: LTO, sodium-ion, lithium-metal and LMFP have no
suitable published parameter set. PyBaMM ships 19 sets, and the four used above
are the only ones that match a chemistry in this library: there is no LTO or
lithium-metal set at all, and its single sodium-ion set (Chayambuka2022) is a
hard-carbon / NVPF cell, whose NASICON cathode plateaus do not belong on the
hard-carbon / layered-oxide cells in this library. BattMo, PyBOP and BatteryML
were checked too: BattMo's documented cell sets are Chen 2020
(NMC811/SiOx-graphite) and Xu 2015 (LFP/graphite), PyBOP carries no parameter
data of its own, and BatteryML's datasets cover LCO, LFP, NMC and NCA against
graphite. Open-dataset searches turned up no numeric OCV table for lithium-metal
cells, only capacity-fade CSV and half-cell material data for LTO, and nothing
numeric for LMFP. So LMFP keeps the measured C/10 curve, sodium-ion and LTO keep
the digitised measured curves, and Li-metal keeps the derived NMC shape: each is
still better than a curve fitted to a different cell.

These are still defaults: a single cell's measured OCV differs, and LMFP in
particular depends strongly on the Mn:Fe ratio. That is why the app calls them
defaults and lets you calibrate against your own data.

Chemistry ids and the order they are shown in follow the library. The database
is rebuilt from this module by backend/tools/rebuild_db.py.
"""
