def _pchip_slopes(xs, ys):
    """Fritsch-Carlson derivatives: monotone cubic without overshoot."""
    n = len(xs)
    h = [xs[i + 1] - xs[i] for i in range(n - 1)]
    d = [(ys[i + 1] - ys[i]) / h[i] for i in range(n - 1)]
    m = [0.0] * n

    # one-sided ends, limited to keep the first/last interval monotone
    m[0] = ((2 * h[0] + h[1]) * d[0] - h[0] * d[1]) / (h[0] + h[1]) if n > 2 else d[0]
    m[-1] = ((2 * h[-1] + h[-2]) * d[-1] - h[-1] * d[-2]) / (h[-1] + h[-2]) if n > 2 else d[-1]
    if m[0] * d[0] <= 0:
        m[0] = 0.0
    elif abs(m[0]) > 3 * abs(d[0]):
        m[0] = 3 * d[0]
    if m[-1] * d[-1] <= 0:
        m[-1] = 0.0
    elif abs(m[-1]) > 3 * abs(d[-1]):
        m[-1] = 3 * d[-1]

    for i in range(1, n - 1):
        if d[i - 1] * d[i] <= 0:
            m[i] = 0.0
        else:
            w1 = 2 * h[i] + h[i - 1]
            w2 = h[i] + 2 * h[i - 1]
            m[i] = (w1 + w2) / (w1 / d[i - 1] + w2 / d[i])
    return m


def _pchip(xs, ys, x):
    if x <= xs[0]:
        return ys[0]
    if x >= xs[-1]:
        return ys[-1]
    lo, hi = 0, len(xs) - 1
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if xs[mid] <= x:
            lo = mid
        else:
            hi = mid
    h = xs[hi] - xs[lo]
    t = (x - xs[lo]) / h
    m = _pchip_slopes(xs, ys)
    h00 = 2 * t ** 3 - 3 * t ** 2 + 1
    h10 = t ** 3 - 2 * t ** 2 + t
    h01 = -2 * t ** 3 + 3 * t ** 2
    h11 = t ** 3 - t ** 2
    return (h00 * ys[lo] + h10 * h * m[lo] + h01 * ys[hi] + h11 * h * m[hi])


def ocv_table(anchors, points=101):
    """101 OCV values over SOC 0..100 % from (percent, volt) anchors."""
    xs = [float(p) for p, _ in anchors]
    ys = [float(v) for _, v in anchors]
    if xs[0] != 0 or xs[-1] != 100:
        raise ValueError("OCV anchors must start at 0 % and end at 100 % SOC")
    if any(b <= a for a, b in zip(xs, xs[1:])):
        raise ValueError("OCV anchors must be ordered by increasing SOC")
    if any(b < a for a, b in zip(ys, ys[1:])):
        raise ValueError("OCV anchors must not fall as SOC rises")
    return [round(_pchip(xs, ys, 100.0 * i / (points - 1)), 4) for i in range(points)]


def _c(cid, name, order, nominal_v, v_max, v_min, r_k, r1_ratio, tau_s,
       arrhenius_b, temp_min_c, temp_max_c, anchors):
    return {
        "id": cid,
        "name": name,
        "sort_order": order,
        "nominal_v": nominal_v,
        "v_max": v_max,
        "v_min": v_min,
        "r_k": r_k,
        "r1_ratio": r1_ratio,
        "tau_s": tau_s,
        "arrhenius_b": arrhenius_b,
        "temp_min_c": temp_min_c,
        "temp_max_c": temp_max_c,
        "anchors": anchors,
    }


