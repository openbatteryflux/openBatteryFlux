#!/usr/bin/env python3
"""Fit the default OCV curves to PyBaMM's published parameter sets.

PyBaMM ships parameter sets whose open-circuit potentials come from published
measurements: NCA_Kim2011 (Kim et al. 2011, graphite/NCA pouch), Ecker2015
(Ecker et al. 2015, graphite/NMC commercial pouch), Prada2013 (Prada et al.
2013, graphite/LFP), Ramadass2004 (Ramadass et al. 2004, graphite/LCO) and
Chayambuka2022 (sodium-ion).

The equilibrium OCV of a set is read by solving its single-particle model with
zero current at each initial SOC: nothing moves, so the terminal voltage is the
open-circuit voltage of that state. Voltage-limit events are removed first,
because several sets sit exactly on a cut-off at 0 % or 100 % SOC and PyBaMM
then refuses to solve.

Two properties of these sets matter before the values can be used here:

  * SOC in a parameter set is defined by its stoichiometry window, which ends at
    the voltage cut-offs. Its OCV at 0 % SOC is therefore the *loaded* cut-off
    (2.5 V for the NMC set, 2.0 V for LFP), not the rested voltage this library
    records, which is several hundred millivolts higher for a fully discharged
    cell.
  * Because of that, mapping the set affinely onto the library's endpoints
    squeezes the plateau and inflates the middle (it puts NMC at 3.94 V at
    50 % SOC, against 3.70 V measured).

So the curve is not rescaled: it is *warped*, i.e. its voltage axis is passed
through a monotone cubic map whose knots are the library's own measured
voltages at 0, 50 and 100 % SOC. The result passes through those three measured
points exactly, keeps the set's shape between them, and stays monotone.

Sodium-ion is computed but not written: its OCP functions show that
Chayambuka2022 is a hard-carbon / NVPF (Na3V2(PO4)2F3) cell, and the NASICON
cathode plateaus do not belong on the hard-carbon / layered-oxide cells this
library lists - warped onto the measured sodium curve they produce a 197 mV step
per 1 % SOC. The measured sodium-ion table in chem_profiles.py is kept instead.

Writes backend/tools/ocv_fits.py. Needs pybamm, which is a generation-time tool
and not a runtime dependency of the app:

    .venv/bin/pip install pybamm
    .venv/bin/python backend/tools/fit_ocv_pybamm.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import pybamm

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from chem_profiles import _pchip  # noqa: E402

# The library's measured voltages at 0, 50 and 100 % SOC for each chemistry,
# taken from the tables in chem_profiles.py before the fit. They are the knots
# of the warp, and they are duplicated here so this script does not depend on
# the state of the file it is regenerating.
WARP_KNOTS = {
    "nmc": (3.345, 3.698, 4.124),
    "nca": (3.355, 3.712, 4.145),
    "lfp": (2.893, 3.286, 3.392),
    "lco": (3.495, 3.848, 4.200),
    "na": (2.200, 3.013, 3.920),
}

FITS = {
    "nmc": ("Ecker2015", "NMC_ECKER2015"),
    "nca": ("NCA_Kim2011", "NCA_KIM2011"),
    "lfp": ("Prada2013", "LFP_PRADA2013"),
    "lco": ("Ramadass2004", "LCO_RAMADASS2004"),
    "na": ("Chayambuka2022", "NA_CHAYAMBUKA2022"),
}

# written to ocv_fits.py; sodium-ion is deliberately absent (see module docstring)
WRITTEN = ("nmc", "nca", "lfp", "lco")

HEADER = '''"""Default OCV tables fitted to PyBaMM parameter sets.

Generated by backend/tools/fit_ocv_pybamm.py - do not edit by hand. Each table
holds 101 voltages, one per 1 % SOC, from a PyBaMM parameter set:

  NMC_ECKER2015      Ecker2015      Ecker et al. 2015, graphite/NMC pouch
  NCA_KIM2011        NCA_Kim2011    Kim et al. 2011, graphite/NCA pouch
  LFP_PRADA2013      Prada2013      Prada et al. 2013, graphite/LFP
  LCO_RAMADASS2004   Ramadass2004   Ramadass et al. 2004, graphite/LCO

The equilibrium OCV of each set was read at zero current, then warped with a
monotone map through this library's measured 0, 50 and 100 % SOC voltages, so
each curve passes through those points and keeps the published shape between
them. Sodium-ion, LTO and lithium-metal have no suitable set: the only
sodium-ion set is a hard-carbon / NVPF cell, not the layered-oxide cells this
library lists.
"""

'''


def curve(set_name: str, knots):
    """101 equilibrium OCV values of a PyBaMM set, warped to the given knots."""
    pv = pybamm.ParameterValues(set_name)
    pv["Current function [A]"] = 0.0
    model = pybamm.lithium_ion.SPM()
    model.events = []
    sim = pybamm.Simulation(model, parameter_values=pv)
    raw = []
    for i in range(101):
        sol = sim.solve([0, 1], initial_soc=i / 100, t_interp=[0, 1])
        raw.append(float(sol["Terminal voltage [V]"].entries[0]))
    if any(b < a - 1e-12 for a, b in zip(raw, raw[1:])):
        raise SystemExit(f"{set_name}: PyBaMM OCV is not monotone")
    xs = [raw[0], raw[50], raw[100]]
    warped = [_pchip(xs, list(knots), v) for v in raw]
    # PCHIP is monotone in x; guard the rounded output as well
    for i in range(1, len(warped)):
        warped[i] = max(warped[i], warped[i - 1])
    return [round(v, 4) for v in warped]


def main():
    out = {}
    for cid, (set_name, const) in FITS.items():
        values = curve(set_name, WARP_KNOTS[cid])
        step = max(b - a for a, b in zip(values, values[1:])) * 1000
        print(f"{cid:9s} <- {set_name:16s} {values[0]:.3f} -> {values[-1]:.3f} V"
              f"  max {step:.0f} mV per 1 % SOC"
              f"{'' if cid in WRITTEN else '  (not written: different sub-chemistry)'}")
        out[const] = values

    lines = [HEADER]
    for _, const in FITS.values():
        if const not in out:
            continue
        lines.append(f"{const} = [\n")
        values = out[const]
        for i in range(0, len(values), 10):
            chunk = ", ".join(f"{v:.4f}" for v in values[i:i + 10])
            lines.append(f"    {chunk},\n")
        lines.append("]\n\n")
    target = HERE / "ocv_fits.py"
    target.write_text("".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"\nwrote {target}")


if __name__ == "__main__":
    main()
